export const PRODUCTS_BY_SLUG = new Map(PRODUCTS.map((product) => [product.slug, product]))

export function productBySlug(slug: string) {
  return PRODUCTS_BY_SLUG.get(slug)
}

export function productsBySlugs(slugs: string[]) {
  return slugs.map(productBySlug).filter((product): product is Product => Boolean(product))
}

/** Sản phẩm liên quan: ưu tiên cùng nhóm hoá chất, sau đó cùng ngành ứng dụng. */
export function relatedProducts(product: Product, limit = 4) {
  const sameGroup = PRODUCTS.filter(
    (candidate) => candidate.slug !== product.slug && candidate.groupSlug === product.groupSlug,
  )
  const sameIndustry = PRODUCTS.filter(
    (candidate) =>
      candidate.slug !== product.slug &&
      candidate.groupSlug !== product.groupSlug &&
      candidate.industrySlugs.some((slug) => product.industrySlugs.includes(slug)),
  )
  return [...sameGroup, ...sameIndustry].slice(0, limit)
}
